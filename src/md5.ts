/** Per-round left-rotate counts from RFC 1321. */
const SHIFT = [
  7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 5, 9, 14, 20, 4,
  11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21,
];

/** T[i] = floor(2^32 * abs(sin(i))) for i = 1..64. */
const K = new Uint32Array(64);
for (let i = 0; i < 64; i++) {
  K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 0x100000000) >>> 0;
}

/**
 * MD5 of the given bytes.
 * Web Crypto does not offer MD5, and readFlash compares this digest with the stub.
 * @param {Uint8Array} data Bytes to hash.
 * @returns {Uint8Array} 16-byte MD5 digest.
 */
export function md5(data: Uint8Array): Uint8Array {
  const bitLength = data.length * 8;
  // 0x80, then zeros, so the length is 56 mod 64 before the 8-byte bit count.
  const mod = (data.length + 1) % 64;
  const zeros = mod <= 56 ? 56 - mod : 120 - mod;
  const padded = new Uint8Array(data.length + 1 + zeros + 8);
  padded.set(data);
  padded[data.length] = 0x80;
  const paddedView = new DataView(padded.buffer);
  paddedView.setUint32(padded.length - 8, bitLength >>> 0, true);
  paddedView.setUint32(padded.length - 4, Math.floor(bitLength / 0x100000000), true);

  let a0 = 0x67452301;
  let b0 = 0xefcdab89;
  let c0 = 0x98badcfe;
  let d0 = 0x10325476;

  const words = new Uint32Array(16);
  for (let offset = 0; offset < padded.length; offset += 64) {
    for (let i = 0; i < 16; i++) {
      words[i] = paddedView.getUint32(offset + i * 4, true);
    }

    let a = a0;
    let b = b0;
    let c = c0;
    let d = d0;
    for (let i = 0; i < 64; i++) {
      let f = 0;
      let g = 0;
      if (i < 16) {
        f = (b & c) | (~b & d);
        g = i;
      } else if (i < 32) {
        f = (d & b) | (~d & c);
        g = (5 * i + 1) % 16;
      } else if (i < 48) {
        f = b ^ c ^ d;
        g = (3 * i + 5) % 16;
      } else {
        f = c ^ (b | ~d);
        g = (7 * i) % 16;
      }
      f = (f + a + K[i] + words[g]) >>> 0;
      const rotated = ((f << SHIFT[i]) | (f >>> (32 - SHIFT[i]))) >>> 0;
      a = d;
      d = c;
      c = b;
      b = (b + rotated) >>> 0;
    }

    a0 = (a0 + a) >>> 0;
    b0 = (b0 + b) >>> 0;
    c0 = (c0 + c) >>> 0;
    d0 = (d0 + d) >>> 0;
  }

  const out = new Uint8Array(16);
  const outView = new DataView(out.buffer);
  outView.setUint32(0, a0, true);
  outView.setUint32(4, b0, true);
  outView.setUint32(8, c0, true);
  outView.setUint32(12, d0, true);
  return out;
}
